import { createHash } from 'node:crypto'

// 人物、日期与聊天均为合成材料；评分事实不进入模型输入。
function makeCase(days) {
  const messages = days.flatMap(([date, entries]) => entries.map(([isSelf, text, replyToMessageId], index) => ({
    senderName: isSelf ? '合成本人' : '合成对方', isSelf, text,
    sentAtMs: Date.parse(`${date}T09:00:00+08:00`) + index * 11 * 60_000,
    replyToMessageId: replyToMessageId === undefined ? null : String(replyToMessageId),
  }))).map((message, index) => ({
    id: String(index + 1),
    revision: createHash('sha256').update(JSON.stringify([index + 1, message])).digest('hex'),
    ...message,
  }))
  if (messages.length !== 120) throw new Error('每组合成材料须包含120条消息。')
  return {
    scope: { kind: 'dates', startDate: days[0][0], endDate: days.at(-1)[0], timezone: 'Asia/Shanghai' },
    messages,
    excluded: {
      id: '999', revision: createHash('sha256').update('long-comparison-excluded').digest('hex'),
      senderName: '合成对方', isSelf: false, text: '这条范围外合成消息只留在本地，不属于本次聊天分析材料。',
      sentAtMs: Date.parse('2026-11-15T09:00:00+08:00'), replyToMessageId: null,
    },
  }
}

