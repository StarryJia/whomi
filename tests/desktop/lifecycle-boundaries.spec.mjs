import { _electron as electron, expect, test } from '@playwright/test'
import { createServer } from 'node:http'
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { basename, dirname, join, resolve } from 'node:path'

test('切换与新建 AI 对话结束旧引用查看，保留各自草稿', async () => {
  test.setTimeout(90000)
  const directory = await mkdtemp(join(tmpdir(), 'whomi-runtime-lifecycle-'))
  const evidence = resolve(process.env.WHOMI_AUDIT_EVIDENCE || 'artifacts/state-lifecycle')
  const server = createServer((request, response) => {
    request.resume()
    request.on('end', () => {
      response.writeHead(200, { 'Content-Type': 'text/event-stream' })
      response.end(`data: ${JSON.stringify({ choices: [{ index: 0, delta: { content: '这是虚构会话的本机验收回答。' }, finish_reason: null }] })}\n\ndata: ${JSON.stringify({ choices: [{ index: 0, delta: {}, finish_reason: 'stop' }] })}\n\ndata: [DONE]\n\n`)
    })
  })
  let app
  try {
    await mkdir(evidence, { recursive: true })
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
    await writeFile(join(directory, 'probe.cjs'), `module.exports = writer => {
      writer.exec("INSERT INTO conversations(id,title,kind,created_at_ms) VALUES(1,'虚构 · 状态边界审查','direct',0); INSERT INTO source_conversations(id,conversation_id,platform,namespace) VALUES(1,1,'fixture','lifecycle'); INSERT INTO memberships(id,conversation_id,source_conversation_id,source_key,display_name) VALUES(1,1,1,'me','小禾'),(2,1,1,'friend','小林'); INSERT INTO self_confirmations(conversation_id,member_id,status,source) VALUES(1,1,'confirmed','user'); INSERT INTO messages(id,conversation_id,member_id,sender_kind,sender_name,kind,text,ordinal,sent_at_ms) VALUES(1,1,2,'member','小林','text','周六十点在车站见。',0,1761700000000),(2,1,1,'member','小禾','text','好，我会提前出发。',1,1761700060000); INSERT INTO conversation_summaries(conversation_id,message_count,member_count,status) VALUES(1,2,2,'ready');")
      return async () => true
    }`)
    const launch = () => electron.launch({ args: [resolve('out/main/index.cjs'), '--whomi-runtime-test'], env: { ...process.env, WHOMI_RUNTIME_TEST: directory } })
    app = await launch()
    let page = await app.firstWindow()
    await page.evaluate(async baseUrl => {
      const provider = await window.whomi.settings.saveProvider({ name: '本机状态验收', baseUrl, enabled: true, apiKey: 'fixture-only' })
      const model = await window.whomi.settings.saveModel({ providerId: provider.id, label: '虚构验收模型', model: 'local', enabled: true, contextWindow: 32000, maxTokens: 256 })
      await window.whomi.settings.selectModel('conversation', model.id)
    }, `http://127.0.0.1:${server.address().port}/v1`)
    await app.close()
    // 资料已保存，重启时探针只提供空操作。
    await writeFile(join(directory, 'probe.cjs'), 'module.exports = () => async () => true')
    app = await launch()
    page = await app.firstWindow()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 900))
    const button = name => page.getByRole('button', { name, exact: true })
    const shot = name => page.screenshot({ path: join(evidence, `${name}.png`), animations: 'disabled' })
    await expect(page.locator('.startup-intro')).toHaveCount(0)
    if (await button('展开侧栏').isVisible()) await button('展开侧栏').click()
    await button('展开会话列表').click()
    await button('虚构 · 状态边界审查').click()
    await button('选择消息').click()
    await page.getByRole('option', { name: '小林：周六十点在车站见。', exact: true }).click()
    await button('选择消息').click()
    await button('AI 对话').click()
    const draft = page.getByRole('textbox', { name: '向 AI 提问' })
    await draft.fill('对话 A：核对见面时间')
    await button('发送给 AI').click()
    await expect(page.getByRole('log')).toContainText('这是虚构会话的本机验收回答。', { timeout: 30000 })
    await draft.fill('A 的未发送草稿')
    await button('1 条引用').click()
    await expect(page.locator('.message-reference-target')).toHaveCount(1)
    await shot('01-reference-in-a')
    await button('新建 AI 对话').click()
    await expect(draft).toHaveValue('')
    await shot('02-new-thread')
    await expect.soft(page.locator('.message-reference-target')).toHaveCount(0)
    await draft.fill('对话 B：另一件事')
    await button('发送给 AI').click()
    await expect(page.getByRole('log')).toContainText('这是虚构会话的本机验收回答。', { timeout: 30000 })
    await draft.fill('B 的未发送草稿')
    await button('显示对话列表').click()
    await page.getByRole('navigation', { name: 'AI 对话列表' }).getByRole('button', { name: '对话 A：核对见面时间', exact: true }).click()
    await expect(draft).toHaveValue('A 的未发送草稿')
    await button('1 条引用').click()
    await expect(page.locator('.message-reference-target')).toHaveCount(1)
    await button('显示对话列表').click()
    await page.getByRole('navigation', { name: 'AI 对话列表' }).getByRole('button', { name: '对话 B：另一件事', exact: true }).click()
    await expect(draft).toHaveValue('B 的未发送草稿')
    await shot('03-switched-to-b')
    await expect.soft(page.locator('.message-reference-target')).toHaveCount(0)
    await button('生成统计').click()
    await expect(page.getByRole('region', { name: '生成统计' })).toBeVisible()
    const close = button('关闭 AI 对话')
    for (let step = 0; step < 12 && !await close.evaluate(element => element === document.activeElement); step += 1) {
      await page.keyboard.press('Shift+Tab')
    }
    await expect(close).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('complementary', { name: 'AI 对话' })).not.toBeVisible()
    await shot('04-closed-statistics')
    await expect.soft(page.getByRole('region', { name: '生成统计' })).toHaveCount(0)

    await app.evaluate(({ BrowserWindow }) => {
      const window = BrowserWindow.getAllWindows()[0]
      window.setMinimumSize(320, 600)
      window.setSize(360, 800)
    })
    await expect.poll(() => page.evaluate(() => window.innerWidth)).toBeLessThanOrEqual(360)
    await button('AI 对话').click()
    await button('显示对话列表').click()
    await page.getByRole('navigation', { name: 'AI 对话列表' }).getByRole('button', { name: '对话 A：核对见面时间', exact: true }).click()
    await button('1 条引用').click()
    await expect(page.getByRole('complementary', { name: 'AI 对话' })).not.toBeVisible()
    await expect(page.locator('.message-reference-target')).toHaveCount(1)
    await shot('07-narrow-reference')
    await button('AI 对话').click()
    await button('显示对话列表').click()
    await page.getByRole('navigation', { name: 'AI 对话列表' }).getByRole('button', { name: '对话 B：另一件事', exact: true }).click()
    await expect(draft).toHaveValue('B 的未发送草稿')
    await button('关闭 AI 对话').click()
    await shot('08-narrow-switched-to-b')
    await expect.soft(page.locator('.message-reference-target')).toHaveCount(0)
    const focusSession = await page.context().newCDPSession(page)
    // 关闭测试框架的恒定焦点模拟，验收真实窗口失焦。
    await focusSession.send('Emulation.setFocusEmulationEnabled', { enabled: false })
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].focus())
    await expect.poll(() => page.evaluate(() => document.hasFocus())).toBe(true)
    await button('选择消息').click()
    const message = page.getByRole('option', { name: '小林：周六十点在车站见。', exact: true })
    const box = await message.boundingBox()
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down()
    await expect(page.locator('.reader-scroll')).toHaveAttribute('data-selection-dragging', 'true')
    await expect(message).toHaveAttribute('aria-selected', 'true')
    const focusWindowId = await app.evaluate(async ({ BrowserWindow }) => {
      const other = new BrowserWindow({ width: 320, height: 200, show: false, skipTaskbar: true })
      await other.loadURL('about:blank')
      other.show()
      other.focus()
      return other.id
    })
    await expect.poll(() => page.evaluate(() => document.hasFocus())).toBe(false)
    await expect(page.locator('.reader-scroll')).not.toHaveAttribute('data-selection-dragging')
    await expect(message).toHaveAttribute('aria-selected', 'false')
    await page.mouse.up()
    await app.evaluate(({ BrowserWindow }, id) => BrowserWindow.fromId(id)?.close(), focusWindowId)
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].focus())
    await message.click()
    await expect(message).toHaveAttribute('aria-selected', 'true')
    await shot('09-desktop-blur-next-click')
    expect(errors).toEqual([])
  } finally {
    await app?.close()
    server.closeAllConnections()
    await new Promise(resolve => server.close(resolve))
    const target = resolve(directory)
    if (dirname(target) === resolve(tmpdir()) && basename(target).startsWith('whomi-runtime-lifecycle-')) await rm(target, { recursive: true, force: true })
  }
})
