import { test, expect, _electron as electron } from '@playwright/test'
import { createServer } from 'node:http'
import { mkdtemp, mkdir, writeFile, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

test('settings persist real models, process outbound chat, preserve drafts and migrate conversation storage', async () => {
  test.setTimeout(120000)
  const directory = await mkdtemp(join(tmpdir(), 'whomi-runtime-settings-'))
  const destination = await mkdtemp(join(tmpdir(), 'whomi-storage-settings-'))
  const occupied = await mkdtemp(join(tmpdir(), 'whomi-occupied-settings-'))
  await writeFile(join(occupied, 'keep.txt'), 'do not replace')
  const evidence = resolve('release/settings-acceptance-20261030')
  await mkdir(evidence, { recursive: true })
  const requests = []
  let fail = true
  const server = createServer((request, response) => {
    if (request.url === '/v1/models') { response.writeHead(200, { 'Content-Type': 'application/json' }); response.end(JSON.stringify({ data: [{ id: 'synthetic-chat', context_length: 8000, max_output_tokens: 1000 }, { id: 'synthetic-analysis' }] })); return }
    let body = ''
    request.on('data', chunk => { body += chunk })
    request.on('end', () => {
      const input = JSON.parse(body); requests.push(input)
      if (fail) { response.writeHead(401); response.end(JSON.stringify({ error: { message: 'synthetic failure' } })); return }
      response.writeHead(200, { 'Content-Type': 'text/event-stream' })
      response.write(`data: ${JSON.stringify({ id: 'synthetic', choices: [{ index: 0, delta: { content: '合成验收回答' }, finish_reason: null }] })}\n\n`)
      response.end(`data: ${JSON.stringify({ id: 'synthetic', choices: [{ index: 0, delta: {}, finish_reason: 'stop' }], usage: { prompt_tokens: 20, completion_tokens: 10, total_tokens: 30 } })}\n\ndata: [DONE]\n\n`)
    })
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  await writeFile(join(directory, 'probe.cjs'), `module.exports=(writer)=>async method=>{
    if(method!=='probe.seed')throw Error('Unsupported');
    writer.exec(\`INSERT INTO conversations(id,title,kind,created_at_ms) VALUES(1,'设置验收 · 虚构会话','direct',0);
    INSERT INTO source_conversations(id,conversation_id,platform,namespace) VALUES(1,1,'example','settings');
    INSERT INTO memberships(id,conversation_id,source_conversation_id,source_key,display_name) VALUES(1,1,1,'me','示例甲');
    INSERT INTO self_confirmations(conversation_id,member_id,status,source) VALUES(1,1,'confirmed','user');
    INSERT INTO messages(id,conversation_id,member_id,sender_kind,sender_name,kind,text,ordinal) VALUES(1,1,1,'member','示例甲','text','示例甲的电话 13800138000，邮箱 example@example.com',0);\`);
    return true;
  }`)
  let app
  const launch = () => electron.launch({ ...(process.env.WHOMI_PACKAGED_EXECUTABLE ? { executablePath: resolve(process.env.WHOMI_PACKAGED_EXECUTABLE), args: ['--whomi-runtime-test'] } : { args: [resolve('out/main/index.cjs'), '--whomi-runtime-test'] }), env: { ...process.env, WHOMI_RUNTIME_TEST: directory } })
  try {
    app = await launch()
    let page = await app.firstWindow()
    await expect(page.getByRole('button', { name: '设置', exact: true })).toBeVisible()
    await app.evaluate(async () => globalThis.__whomiRuntimeProbe.request('probe.seed', null))
    await page.reload()
    await page.getByRole('button', { name: '展开会话列表' }).click()
    await page.getByRole('button', { name: '设置验收 · 虚构会话', exact: true }).click()
    const draft = page.getByRole('textbox', { name: '向 AI 提问', exact: true })
    await draft.fill('设置后保留的草稿')
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await expect(page.getByRole('button', { name: '添加服务商', exact: true })).toBeVisible()
    await page.screenshot({ path: join(evidence, '01-model-empty.png') })
    await page.getByRole('button', { name: '添加服务商', exact: true }).click()
    await page.getByLabel('服务商名称', { exact: true }).fill('本地合成验收')
    await page.getByLabel('接口地址', { exact: true }).fill(`http://127.0.0.1:${server.address().port}/v1`)
    await page.getByLabel('密钥', { exact: true }).fill('test-only-secret')
    await page.getByRole('dialog', { name: '添加服务商' }).getByRole('button', { name: '保存', exact: true }).click()
    await expect(page.getByLabel('替换密钥', { exact: true })).toHaveValue('')
    await page.getByRole('button', { name: '同步模型', exact: true }).click()
    await page.getByRole('button', { name: '添加synthetic-chat', exact: true }).click()
    await page.getByRole('button', { name: '关闭本地合成验收 模型', exact: true }).click()
    await expect(page.locator('.ms-model-row')).toHaveCount(1)
    await page.getByRole('button', { name: '手动添加', exact: true }).click()
    await page.getByLabel('模型标识', { exact: true }).fill('synthetic-analysis')
    await page.getByLabel('显示名称', { exact: true }).fill('合成分析')
    await page.getByLabel('上下文长度', { exact: true }).fill('8000')
    await page.getByLabel('最大输出长度', { exact: true }).fill('1000')
    await page.getByRole('button', { name: '添加模型', exact: true }).click()
    await page.getByRole('button', { name: '检测synthetic-chat', exact: true }).click()
    await expect(page.getByText('检测失败', { exact: true })).toBeVisible({ timeout: 15000 })
    fail = false
    await page.getByRole('button', { name: '检测synthetic-chat', exact: true }).click()
    await expect(page.getByText('连接成功', { exact: true })).toBeVisible({ timeout: 15000 })
    expect(JSON.stringify(requests)).not.toMatch(/13800138000|example@example\.com|设置后保留的草稿/)
    await page.screenshot({ path: join(evidence, '02-provider-models.png') })
    await page.getByRole('button', { name: '消息处理', exact: true }).click()
    await page.getByRole('switch', { name: '智能去噪', exact: true }).click()
    await expect.poll(() => page.evaluate(async () => (await window.whomi.settings.get()).processing.denoise)).toBe(true)
    await page.screenshot({ path: join(evidence, '03-message-processing.png'), fullPage: true })
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(960, 720))
    await page.screenshot({ path: join(evidence, '04-narrow-processing.png') })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    expect(await page.locator('.sp-sidebar').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.getByRole('button', { name: '关于whomi', exact: true }).click()
    await app.evaluate(({ shell }) => { globalThis.__openedLinks = []; shell.openExternal = async url => { globalThis.__openedLinks.push(url) } })
    await page.getByRole('link', { name: /项目仓库/ }).click()
    await expect.poll(() => app.evaluate(() => globalThis.__openedLinks)).toEqual(['https://github.com/StarryJia/whomi'])
    await page.getByRole('button', { name: '第三方声明', exact: true }).click()
    await expect(page.getByRole('dialog', { name: '第三方声明' })).toContainText('MIT License')
    await page.keyboard.press('Escape')
    await page.getByRole('switch', { name: '调试模式', exact: true }).click()
    await page.evaluate(() => { location.hash = 'main-content' })
    await page.getByRole('button', { name: '复制诊断信息', exact: true }).click()
    await expect(page.getByText('已复制。', { exact: true })).toBeVisible()
    const diagnosticText = await app.evaluate(({ clipboard }) => clipboard.readText())
    expect(JSON.parse(diagnosticText)).toMatchObject({ version: JSON.parse(await readFile('package.json', 'utf8')).version, platform: process.platform })
    expect(diagnosticText).not.toMatch(/test-only-secret|13800138000|example@example\.com/)
    await page.screenshot({ path: join(evidence, '08-about-diagnostics.png') })
    await app.evaluate(({ BrowserWindow }) => { const window = BrowserWindow.getAllWindows()[0]; window.setMinimumSize(320, 320); window.setSize(360, 800) })
    await page.getByRole('button', { name: '分类', exact: true }).click()
    await page.getByRole('button', { name: '模型服务', exact: true }).click()
    await page.getByRole('button', { name: '本地合成验收', exact: true }).click()
    await expect(page.getByLabel('接口地址', { exact: true })).toBeVisible()
    await page.screenshot({ path: join(evidence, '09-narrow-model.png') })
    expect(await page.locator('.ms-detail').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(960, 720))
    await page.getByRole('button', { name: '返回', exact: true }).click()
    await expect(draft).toHaveValue('设置后保留的草稿')
    const state = await page.evaluate(() => window.whomi.settings.get())
    const chatId = state.models.find(model => model.model === 'synthetic-chat').id
    const analysisId = state.models.find(model => model.model === 'synthetic-analysis').id
    await page.getByRole('combobox', { name: '对话模型' }).click()
    await page.getByRole('option', { name: 'synthetic-chat', exact: true }).click()
    await page.getByRole('button', { name: '会话分析', exact: true }).click()
    await page.getByRole('combobox', { name: '分析模型' }).click()
    await page.getByRole('option', { name: '合成分析', exact: true }).click()
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: '选择消息', exact: true }).click()
    await page.getByRole('option', { name: /示例甲：示例甲的电话/ }).click()
    await draft.fill('示例甲 example@example.com 13800138000')
    await page.getByRole('button', { name: '发送给 AI', exact: true }).click()
    await expect(page.getByText('合成验收回答', { exact: true })).toBeVisible({ timeout: 30000 })
    expect(JSON.stringify(requests.at(-1))).not.toMatch(/示例甲|13800138000|example@example\.com/)
    expect(JSON.stringify(requests.at(-1))).toContain('U1')
    expect((await page.evaluate(() => window.whomi.settings.get())).selectedModels).toEqual({ conversation: chatId, analysis: analysisId })
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await page.getByRole('button', { name: '数据存储', exact: true }).click()
    await app.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }) })
    await page.getByRole('button', { name: '选择保存目录', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, occupied)
    await page.getByRole('button', { name: '选择保存目录', exact: true }).click()
    await expect(page.getByRole('alert')).toBeVisible()
    expect(await readFile(join(occupied, 'keep.txt'), 'utf8')).toBe('do not replace')
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, destination)
    await page.getByRole('button', { name: '选择保存目录', exact: true }).click()
    await page.getByRole('button', { name: '取消', exact: true }).click()
    expect((await page.evaluate(() => window.whomi.settings.getStorage())).path).toBe(directory)
    await page.getByRole('button', { name: '选择保存目录', exact: true }).click()
    await page.screenshot({ path: join(evidence, '05-storage-confirm.png') })
    await page.getByRole('button', { name: '确认迁移', exact: true }).click()
    await expect(page.getByRole('button', { name: '立即重启', exact: true })).toBeVisible({ timeout: 20000 })
    await expect(page.getByRole('button', { name: '返回', exact: true })).toBeDisabled()
    await page.screenshot({ path: join(evidence, '06-storage-completed.png') })
    await app.evaluate(({ app }) => {
      globalThis.__restartCalls = []
      globalThis.__originalQuit = app.quit
      app.relaunch = () => { globalThis.__restartCalls.push('relaunch') }
      app.quit = () => { globalThis.__restartCalls.push('quit') }
    })
    await page.getByRole('button', { name: '立即重启', exact: true }).click()
    await expect.poll(() => app.evaluate(() => globalThis.__restartCalls)).toEqual(['relaunch', 'quit'])
    await app.evaluate(({ app }) => { app.quit = globalThis.__originalQuit })
    await app.close()
    app = await launch()
    page = await app.firstWindow()
    expect((await page.evaluate(() => window.whomi.settings.getStorage())).path).toBe(destination)
    const restored = await page.evaluate(() => window.whomi.settings.get())
    expect(restored.providers[0]).toMatchObject({ hasCredential: true, name: '本地合成验收' })
    expect(JSON.stringify(restored)).not.toContain('test-only-secret')
    expect(restored.processing.denoise).toBe(true)
    await page.getByRole('button', { name: '展开会话列表' }).click()
    await page.getByRole('button', { name: '设置验收 · 虚构会话', exact: true }).click()
    await expect(page.locator('.message-text')).toContainText('13800138000')
    await expect(page.getByRole('combobox', { name: '对话模型' })).toContainText('synthetic-chat')
    await page.getByRole('button', { name: '继续 AI 对话', exact: true }).click()
    await expect(page.getByText('合成验收回答', { exact: true })).toBeVisible()
    await page.getByRole('textbox', { name: '向 AI 提问', exact: true }).fill('迁移后继续')
    await page.getByRole('button', { name: '发送给 AI', exact: true }).click()
    await expect(page.getByText('合成验收回答', { exact: true })).toHaveCount(2, { timeout: 30000 })
    expect(JSON.stringify(requests.at(-1))).not.toMatch(/示例甲|13800138000|example@example\.com/)
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await page.getByRole('switch', { name: '启用服务商', exact: true }).click()
    await expect.poll(() => page.evaluate(async () => (await window.whomi.settings.get()).providers[0].enabled)).toBe(false)
    await page.getByRole('button', { name: '返回', exact: true }).click()
    await expect(page.getByRole('combobox', { name: '对话模型' })).toContainText('暂无可用模型')
    await page.screenshot({ path: join(evidence, '07-model-disabled.png') })
  } finally {
    await app?.close()
    server.closeAllConnections()
    await new Promise(resolve => server.close(resolve))
  }
})
