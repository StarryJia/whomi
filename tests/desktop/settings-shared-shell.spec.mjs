import { test, expect, _electron as electron } from '@playwright/test'
import { mkdir, mkdtemp, realpath, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'

test('设置保留导航和对话草稿，主导航等待有效配置保存后切换', async () => {
  test.setTimeout(90000)
  const temp = await realpath(tmpdir())
  const profile = await mkdtemp(join(temp, 'whomi-runtime-settings-shell-'))
  const moved = await mkdtemp(join(temp, 'whomi-storage-settings-shell-'))
  const evidence = resolve('artifacts/settings-shared-shell')
  await mkdir(evidence, { recursive: true })
  await writeFile(join(profile, 'probe.cjs'), `module.exports = db => () => {
    db.exec("INSERT INTO conversations(id,title,kind,created_at_ms) VALUES(1,'示例会话','direct',0);" +
      "INSERT INTO source_conversations(id,conversation_id,platform,namespace) VALUES(1,1,'example','shared-shell');" +
      "INSERT INTO memberships(id,conversation_id,source_conversation_id,source_key,display_name) VALUES(1,1,1,'me','示例甲');" +
      "INSERT INTO self_confirmations(conversation_id,member_id,status,source) VALUES(1,1,'confirmed','user');" +
      "INSERT INTO messages(id,conversation_id,member_id,sender_kind,sender_name,kind,text,ordinal) VALUES(1,1,1,'member','示例甲','text','这是一条测试消息。',0)")
    return true
  }`)
  const app = await electron.launch({ args: [resolve('out/main/index.cjs'), '--whomi-runtime-test'], env: { ...process.env, WHOMI_RUNTIME_TEST: profile } })
  try {
    expect(await app.evaluate(({ app }) => app.getPath('userData'))).toBe(profile)
    const page = await app.firstWindow()
    const button = name => page.getByRole('button', { name, exact: true })
    const resize = (width, height) => app.evaluate(({ BrowserWindow }, size) => {
      const window = BrowserWindow.getAllWindows()[0]
      window.setMinimumSize(320, 320)
      window.setContentSize(...size)
    }, [width, height])
    await resize(1440, 900)
    await expect(button('设置')).toBeVisible()
    await app.evaluate(() => globalThis.__whomiRuntimeProbe.request('probe.seed', null))
    await page.evaluate(async () => {
      const provider = await window.whomi.settings.saveProvider({ name: '示例服务商', baseUrl: 'http://127.0.0.1:9/v1', enabled: true, apiKey: 'fictional' })
      await window.whomi.settings.saveModel({ providerId: provider.id, model: 'example-chat', label: '示例对话模型', enabled: true, contextWindow: 8192, maxTokens: 1024 })
    })
    await page.reload()
    await expect(page.locator('.startup-intro')).toHaveCount(0, { timeout: 15000 })
    if (await button('展开侧栏').isVisible()) await button('展开侧栏').click()
    await button('展开会话列表').click()
    await button('示例会话').click()
    await button('AI 对话').click()
    const draft = page.getByRole('textbox', { name: '向 AI 提问', exact: true })
    await draft.fill('只用于验证的草稿')
    const divider = page.getByRole('separator', { name: '调整主导航宽度' })
    await divider.press('ArrowRight')
    await expect.poll(() => divider.getAttribute('aria-valuenow')).not.toBe('240')
    await expect.poll(() => page.locator('#app-sidebar').evaluate(el => el.getBoundingClientRect().width))
      .toBe(await page.evaluate(() => Number(localStorage.getItem('whomi:pane:navigation'))))
    const brand = page.getByRole('link', { name: 'Whomi 首页' })
    const before = await brand.boundingBox()
    const sidebar = page.locator('#app-sidebar')
    const sidebarBefore = await sidebar.boundingBox()
    await button('设置').click()
    await expect(button('设置')).toHaveAttribute('aria-current', 'page')
    await expect(page.getByRole('main')).toHaveCount(1)
    expect(await brand.boundingBox()).toEqual(before)
    expect(await sidebar.boundingBox()).toEqual(sidebarBefore)
    const address = page.getByLabel('接口地址', { exact: true })
    await expect(address).toBeVisible()
    await page.screenshot({ path: join(evidence, 'desktop.png') })
    await button('返回').click()
    await expect(draft).toHaveValue('只用于验证的草稿')
    await button('设置').click()
    await address.fill('无效地址')
    await button('记忆仓库').click()
    await expect(address).toBeVisible()
    await expect(address).toHaveValue('无效地址')
    await address.fill('http://127.0.0.1:9/v2')
    await button('记忆仓库').click()
    await expect(button('记忆仓库')).toHaveAttribute('aria-current', 'page')
    expect(await page.evaluate(async () => (await window.whomi.settings.get()).providers[0].baseUrl)).toBe('http://127.0.0.1:9/v2')
    await button('收起侧栏').click()
    await button('设置').click()
    await expect(button('展开侧栏')).toBeVisible()
    await resize(360, 800)
    await button('示例服务商').click()
    await expect(address).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: join(evidence, 'narrow.png') })
    await button('分类').click()
    await button('系统提示词').click()
    await button('编辑AI 对话').click()
    const prompt = page.getByRole('textbox', { name: '提示词内容' })
    await prompt.fill('用于确认离开的测试提示词。')
    await button('取消').click()
    await button('继续编辑').click()
    await expect(prompt).toHaveValue('用于确认离开的测试提示词。')
    await button('取消').click()
    await button('放弃修改').click()
    await expect(prompt).toHaveCount(0)
    await button('返回').click()
    await expect(button('记忆仓库')).toHaveAttribute('aria-current', 'page')
    await resize(960, 720)
    await button('设置').click()
    await button('数据存储').click()
    await app.evaluate(({ dialog }, path) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] })
    }, moved)
    await button('选择保存目录').click()
    await button('确认迁移').click()
    await expect(button('立即重启')).toBeVisible()
    await expect(button('返回')).toBeDisabled()
    await expect(page.locator('.sidebar-navigation')).toHaveAttribute('inert', '')
    await expect(button('设置')).toHaveAttribute('aria-current', 'page')
  } finally {
    await app.close()
    for (const directory of [profile, moved]) {
      const actual = await realpath(directory)
      if (actual === directory && dirname(actual) === temp) await rm(actual, { recursive: true, force: true, maxRetries: 3 })
    }
  }
})
